def emit_heading(output: list[str], level: int, text: str) -> None:
    macro = {1: "PART", 2: "H2", 3: "H3", 4: "H4"}[level]
    output.append(f".{macro}BEGIN\n")
    output.append(inline_markup(text) + "\n")
    output.append(f".{macro}END\n")


def emit_paragraph(output: list[str], text: str) -> None:
    output.append(".PP\n")
    output.append(inline_markup(text.strip()) + "\n")


def emit_list_item(output: list[str], text: str, number: str | None = None) -> None:
    output.append(".sp 0.10v\n")
    output.append(".in +0.62c\n")
    output.append(".ti -0.50c\n")
    if number is None:
        prefix = r"\m[Teal]\(bu\m[black]\h'0.14c'"
    else:
        prefix = rf"\m[Teal]{roff_literal(number)}.\m[black]\h'0.14c'"
    output.append(prefix + inline_markup(text) + "\n")
    output.append(".br\n")
    output.append(".in -0.62c\n")


def emit_callout(output: list[str], text: str) -> None:
    upper = text.upper()
    if upper.startswith(("WARNING:", "SAFETY:", "DANGER:")):
        begin, end = "WARNINGBEGIN", "WARNINGEND"
        body = text.split(":", 1)[1].strip()
    elif upper.startswith(("EXPECTED:", "SUCCESS:")):
        begin, end = "CHECKBEGIN", "CHECKEND"
        body = text.split(":", 1)[1].strip()
    else:
        begin, end = "NOTEBEGIN", "NOTEEND"
        body = text.split(":", 1)[1].strip() if ":" in text else text
    output.append(f".{begin}\n")
    output.append(inline_markup(body) + "\n")
    output.append(f".{end}\n")


def split_table_row(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def emit_table(output: list[str], rows: list[list[str]]) -> None:
    columns = len(rows[0])
    if columns == 2:
        widths = ["4.4c", "11.3c"]
    elif columns == 3:
        widths = ["3.7c", "2.7c", "8.0c"]
    elif columns == 4:
        widths = ["2.8c", "2.4c", "3.4c", "5.3c"]
    elif columns == 5:
        widths = ["1.6c", "2.1c", "2.7c", "3.2c", "4.1c"]
    else:
        raise ValueError(f"tables with {columns} columns are not supported")
    output.append(".sp 0.32v\n")
    output.append(".ps 7.9\n")
    output.append(".vs 10.1p\n")
    output.append(".TS\n")
    output.append("tab(@) allbox;\n")
    output.append(" ".join(f"lw({width})" for width in widths) + ".\n")

    def table_line(cells: list[str], *, header: bool = False) -> None:
        rendered: list[str] = []
        for cell in cells:
            content = inline_markup(cell)
            content = content.replace("/", r"/\:").replace("_", r"_\:")
            if header:
                content = r"\f[HB]\m[Navy]" + content + r"\m[black]\fP"
            rendered.append("T{\n" + content + "\nT}")
        output.append("@".join(rendered) + "\n")

    table_line(rows[0], header=True)
    for row in rows[1:]:
        table_line(row)
    output.append(".TE\n")
    output.append(".ps 9.4\n")
    output.append(".vs 12.4p\n")
    output.append(".sp 0.30v\n")


def convert(markdown_lines: list[str]) -> str:
    """Convert the documented Markdown subset into groff source."""
    output: list[str] = []
    paragraph: list[str] = []
    in_code = False
    first_title_seen = False
    index = 0

    def flush_paragraph() -> None:
        if paragraph:
            emit_paragraph(output, " ".join(line.strip() for line in paragraph))
            paragraph.clear()

    while index < len(markdown_lines):
        line = markdown_lines[index].rstrip()

        if line.startswith("```"):
            flush_paragraph()
            if in_code:
                output.append(".CODEEND\n")
                in_code = False
            else:
                output.append(".CODEBEGIN\n")
                in_code = True
            index += 1
            continue

        if in_code:
            output.append(roff_literal(line, code=True) + "\n")
            index += 1
            continue

        if (
            "|" in line
            and index + 1 < len(markdown_lines)
            and re.fullmatch(
                r"\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*",
                markdown_lines[index + 1],
            )
        ):
            flush_paragraph()
            table_rows = [split_table_row(line)]
            index += 2
            while index < len(markdown_lines):
                candidate = markdown_lines[index].rstrip()
                if not candidate.strip() or "|" not in candidate:
                    break
                row = split_table_row(candidate)
                if len(row) != len(table_rows[0]):
                    break
                table_rows.append(row)
                index += 1
            emit_table(output, table_rows)
            continue

        heading = re.match(r"^(#{1,4})\s+(.*)$", line)
        if heading:
            flush_paragraph()
            level = len(heading.group(1))
            if level == 1 and not first_title_seen:
                first_title_seen = True
            else:
                emit_heading(output, level, heading.group(2).strip())
            index += 1
            continue

        if line.strip() == "---":
            flush_paragraph()
            output.append(".RULE\n")
            index += 1
            continue

        if line.strip() == "<!-- PDF_PAGE_BREAK -->":
            flush_paragraph()
            output.append(".bp\n")
            index += 1
            continue

        if line.strip() == "<!-- PDF_KEEP_NEXT -->":
            flush_paragraph()
            output.append(".ne 8v\n")
            index += 1
            continue

        if line.startswith("> "):
            flush_paragraph()
            callout_lines: list[str] = []
            while (
                index < len(markdown_lines)
                and markdown_lines[index].rstrip().startswith("> ")
            ):
                callout_lines.append(markdown_lines[index].rstrip()[2:].strip())
                index += 1
            emit_callout(output, " ".join(callout_lines))
            continue

        numbered = re.match(r"^(\d+)\.\s+(.*)$", line)
        if numbered:
            flush_paragraph()
            emit_list_item(output, numbered.group(2), numbered.group(1))
            index += 1
            continue

        if line.startswith("- "):
            flush_paragraph()
            emit_list_item(output, line[2:])
            index += 1
            continue

        if not line.strip():
            flush_paragraph()
            index += 1
            continue

        paragraph.append(line)
        index += 1

    flush_paragraph()
    if in_code:
        raise ValueError("unclosed fenced code block")
    return "".join(output)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: render-manual.py SOURCE.md OUTPUT.roff", file=sys.stderr)
        return 2
    source = Path(sys.argv[1]).resolve()
    output = Path(sys.argv[2]).resolve()
    metadata, markdown_lines = parse_front_matter(source.read_text(encoding="utf-8"))
    rendered = preamble(metadata, source.name) + convert(markdown_lines)
    output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
