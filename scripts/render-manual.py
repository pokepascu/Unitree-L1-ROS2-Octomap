SPECIAL_CHARACTERS = {
    "\u00a0": " ",
    "\u2018": "'",
    "\u2019": "'",
    "\u201c": '"',
    "\u201d": '"',
    "\u2013": "-",
    "\u2014": "--",
    "\u2026": "...",
    "\u2190": "<-",
    "\u2192": "->",
    "\u2194": "<->",
    "\u2264": "<=",
    "\u2265": ">=",
    "\u2248": "~",
    "\u00d7": "x",
}


def parse_front_matter(text: str) -> tuple[dict[str, str], list[str]]:
    """Return simple key/value front matter and the remaining Markdown lines."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("manual source must begin with --- front matter")
    metadata: dict[str, str] = {}
    end = None
    for index, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            end = index
            break
        if ":" not in line:
            raise ValueError(f"invalid front-matter line: {line}")
        key, value = line.split(":", 1)
        metadata[key.strip()] = value.strip()
    if end is None:
        raise ValueError("manual front matter has no closing ---")
    required = {
        "document_type",
        "title",
        "subtitle",
        "edition",
        "prepared",
        "project_commit",
        "audience",
        "footer",
    }
    missing = sorted(required - metadata.keys())
    if missing:
        raise ValueError(f"missing front-matter keys: {', '.join(missing)}")
    return metadata, lines[end + 1 :]


def replace_special_characters(text: str) -> str:
    """Normalize punctuation unsupported by the PostScript core fonts."""
    for source, replacement in SPECIAL_CHARACTERS.items():
        text = text.replace(source, replacement)
    return text


def roff_literal(text: str, *, code: bool = False) -> str:
    """Escape literal text so it cannot become a groff request or escape."""
    text = replace_special_characters(text)
    text = text.replace("\\", r"\e")
    if code:
        text = text.replace("\t", "    ")
    if text.startswith((".", "'")):
        text = r"\&" + text
    return text


def inline_markup(text: str) -> str:
    """Render the small inline subset used by the manual sources."""
    text = replace_special_characters(text)
    pattern = re.compile(r"(`[^`]+`|\*\*[^*]+\*\*)")
    output: list[str] = []
    cursor = 0
    for match in pattern.finditer(text):
        output.append(roff_literal(text[cursor : match.start()]))
        token = match.group(0)
        if token.startswith("`"):
            output.append(r"\f[C]" + roff_literal(token[1:-1], code=True) + r"\fP")
        else:
            output.append(r"\f[HB]" + roff_literal(token[2:-2]) + r"\fP")
        cursor = match.end()
    output.append(roff_literal(text[cursor:]))
    rendered = "".join(output).replace('"', r"\(dq")
    if rendered.startswith((".", "'")):
        rendered = r"\&" + rendered
    return rendered


def roff_string(text: str) -> str:
    """Escape a plain value embedded directly in a groff definition."""
    return roff_literal(text).replace('"', r"\(dq")


